CREATE TABLE IF NOT EXISTS game_profiles (
  profile_id CHAR(36) NOT NULL PRIMARY KEY,
  runs INT UNSIGNED NOT NULL DEFAULT 0,
  play_seconds INT UNSIGNED NOT NULL DEFAULT 0,
  best_room TINYINT UNSIGNED NOT NULL DEFAULT 0,
  best_phase TINYINT UNSIGNED NOT NULL DEFAULT 0,
  best_clear_seconds INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
